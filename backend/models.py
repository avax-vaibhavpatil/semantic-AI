def database_row_to_report_response(row: dict) -> ReportResponse:
    """
    Convert database row to ReportResponse model
    
    Why needed? Database returns dict, we want typed Pydantic model
    
    Usage:
        row = db.fetch_one("SELECT * FROM saved_reports WHERE id=1")
        report = database_row_to_report_response(row)
        return report  # FastAPI auto-converts to JSON
    """
    return ReportResponse(
        report_id=row['report_id'],
        report_name=row['report_name'],
        user_question=row['user_question'],
        generated_sql=row['generated_sql'],
        report_description=row.get('report_description'),
        created_at=row['created_at'],
        updated_at=row.get('updated_at'),
        last_executed_at=row.get('last_executed_at'),
        execution_count=row.get('execution_count', 0),
        is_favorite=row.get('is_favorite', False),
        tags=row.get('tags', []),
        status=row.get('status', 'active')
    )


