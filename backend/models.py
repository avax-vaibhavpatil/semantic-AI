class ReportResponse(BaseModel):
    """
    Complete report information returned by API
    
    Used by:
    - GET /reports/{id} - Get single report
    - POST /reports/save - After saving (returns created report)
    
    Example response:
    {
        "report_id": 42,
        "report_name": "My Sales Dashboard",
        "user_question": "Show top 10 customers",
        "generated_sql": "SELECT ...",
        "created_at": "2025-12-15T10:30:00",
        "last_executed_at": "2025-12-15T11:45:00",
        "execution_count": 5,
        "is_favorite": false,
        "tags": ["sales", "monthly"]
    }
    """
    
    report_id: int = Field(
        ...,
        description="Unique identifier for the report",
        example=42
    )
    
    report_name: str = Field(
        ...,
        description="User-provided report name",
        example="Monthly Sales Leaders"
    )
    
    user_question: str = Field(
        ...,
        description="Original natural language question",
        example="Show top 10 customers by sales"
    )
    
    generated_sql: str = Field(
        ...,
        description="SQL query generated by AI",
        example="SELECT ... FROM ..."
    )
    
    report_description: Optional[str] = Field(
        None,
        description="Report description",
        example="Top performing customers this month"
    )
    
    created_at: datetime = Field(
        ...,
        description="When the report was created",
        example="2025-12-15T10:30:00"
    )
    
    updated_at: Optional[datetime] = Field(
        None,
        description="When the report was last updated"
    )
    
    last_executed_at: Optional[datetime] = Field(
        None,
        description="When the report was last run"
    )
    
    execution_count: int = Field(
        default=0,
        description="How many times this report has been executed",
        example=5
    )
    
    is_favorite: bool = Field(
        default=False,
        description="Whether user marked this as favorite"
    )
    
    tags: List[str] = Field(
        default=[],
        description="Categorization tags",
        example=["sales", "monthly", "executive"]
    )
    
    status: str = Field(
        default="active",
        description="Report status",
        example="active"
    )
    
    class Config:
        orm_mode = True  # Allow creating from database rows


class ReportListItem(BaseModel):
    """
    Abbreviated report info for list views
    
    Used by: GET /reports - List all reports
    
    Why separate from ReportResponse?
    - Lighter weight (no SQL, no description)
    - Faster to load when showing many reports
    - User can click on a report to get full details
      
    Example:
    {
        "report_id": 42,
        "report_name": "Monthly Sales Leaders",
        "created_at": "2025-12-15T10:30:00",
        "last_executed_at": "2025-12-15T11:45:00",
        "execution_count": 5,
        "is_favorite": false,
        "tags": ["sales"]
    }
    """
    
    report_id: int
    report_name: str
    created_at: datetime
    last_executed_at: Optional[datetime]
    execution_count: int
    is_favorite: bool
    tags: List[str]
    
    class Config:
        orm_mode = True


class ReportListResponse(BaseModel):
    """
    Paginated list of reports
    
    Used by: GET /reports?limit=20&offset=0
    
    Example:
    {
        "reports": [...],  // Array of ReportListItem
        "total": 156,      // Total number of user's reports
        "limit": 20,       // How many per page
        "offset": 0        // Current page offset
    }
    """
    
    reports: List[ReportListItem] = Field(
        ...,
        description="List of reports"
    )
    
    total: int = Field(
        ...,
        description="Total number of reports (for pagination)",
        example=156
    )
    
    limit: int = Field(
        default=20,
        description="Number of reports per page",
        example=20
    )
    
    offset: int = Field(
        default=0,
        description="Offset for pagination",
        example=0
    )


class ExecuteReportResponse(BaseModel):
    """
    Result of executing a saved report
    
    Used by: POST /reports/{id}/execute
    
    Returns both report metadata and query results
    
    Example:
    {
        "report": {...},           // Full ReportResponse
        "rows": [...],             // Query results
        "row_count": 10,
        "execution_time_ms": 45
    }
    """
    
    report: ReportResponse = Field(
        ...,
        description="Report metadata"
    )
    
    rows: List[dict] = Field(
        ...,
        description="Query results",
        example=[
            {"customer": "ABC Corp", "sales": 50000},
            {"customer": "XYZ Ltd", "sales": 45000}
        ]
    )
    
    row_count: int = Field(
        ...,
        description="Number of rows returned",
        example=10
    )
    
    execution_time_ms: Optional[int] = Field(
        None,
        description="How long the query took (milliseconds)",
        example=45
    )


