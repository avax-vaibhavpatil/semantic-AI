"""
Data Models for Report Management System

Purpose: Define the structure of data that flows through our API
- Request models: What frontend sends to backend
- Response models: What backend returns to frontend
- Database models: Not here (we use raw SQL), but these match our schema

Benefits of Pydantic:
1. Type safety: Catch bugs at development time
2. Automatic validation: Invalid data rejected before processing
3. Auto-generated docs: FastAPI uses these for OpenAPI/Swagger
4. Serialization: Easy conversion to/from JSON
"""

from pydantic import BaseModel, Field, validator
from typing import Optional, List
from datetime import datetime

# ==============================================================================
# REQUEST MODELS (Frontend → Backend)
# ==============================================================================
# These define what data the frontend must send to our API

class SaveReportRequest(BaseModel):
    """
    Data required to save a new report
    
    User flow:
    1. User asks question → gets results
    2. Clicks "Save Report" → modal appears
    3. Types report name, description, tags → submits
    4. Frontend sends this data to POST /reports/save
    
    Example JSON:
    {
        "report_name": "My Sales Dashboard",
        "user_question": "Show top 10 customers by sales",
        "generated_sql": "SELECT ... ORDER BY ... LIMIT 10",
        "report_description": "Monthly sales leaders report",
        "tags": ["sales", "monthly", "executive"]
    }
    """
    
    # Required fields (must be provided)
    report_name: str = Field(
        ...,  # ... means required
        min_length=1,
        max_length=255,
        description="User-provided name for the report",
        example="Top 10 Customers - December 2025"
    )
    
    user_question: str = Field(
        ...,
        min_length=1,
        description="Original natural language question",
        example="Show me top 10 customers by YTD sales"
    )
    
    generated_sql: str = Field(
        ...,
        min_length=1,
        description="SQL query generated by AI",
        example="SELECT ... FROM ... ORDER BY ..."
    )
    
    # Optional fields (can be null/missing)
    report_description: Optional[str] = Field(
        None,  # None = optional
        max_length=1000,
        description="Longer description of what the report shows",
        example="This report shows the top revenue-generating customers"
    )
    
    tags: Optional[List[str]] = Field(
        default=[],  # Default to empty list if not provided
        description="Categorization tags",
        example=["sales", "customers", "executive"]
    )
    
    # Custom validation: ensure report name isn't just whitespace
    @validator('report_name')
    def name_not_empty(cls, v):
        """Validator: Report name cannot be only spaces"""
        if not v.strip():
            raise ValueError('Report name cannot be empty or whitespace')
        return v.strip()  # Remove leading/trailing spaces
    
    # Custom validation: ensure SQL is not empty
    @validator('generated_sql')
    def sql_not_empty(cls, v):
        """Validator: SQL cannot be empty"""
        if not v.strip():
            raise ValueError('Generated SQL cannot be empty')
        return v.strip()
    
    # Custom validation: limit number of tags
    @validator('tags')
    def limit_tags(cls, v):
        """Validator: Maximum 10 tags per report"""
        if v and len(v) > 10:
            raise ValueError('Maximum 10 tags allowed')
        return v
    
    class Config:
        """Pydantic configuration"""
        # Allow creating model from ORM objects (if we use SQLAlchemy ORM later)
        orm_mode = True
        # Example for API docs
        schema_extra = {
            "example": {
                "report_name": "Monthly Sales Leaders",
                "user_question": "Who are the top 10 customers by sales?",
                "generated_sql": "SELECT gws_cust_code, SUM(gws_ytd_sales) FROM gwanalytics GROUP BY gws_cust_code LIMIT 10",
                "report_description": "Top performing customers this month",
                "tags": ["sales", "monthly"]
            }
        }


class ExecuteReportRequest(BaseModel):
    """
    Parameters for executing a saved report
    
    User flow:
    1. User clicks on a saved report
    2. Frontend calls POST /reports/{id}/execute
    3. Backend runs the SQL and returns fresh data
    """
    
    max_rows: int = Field(
        default=500,
        ge=1,      # ge = greater than or equal to
        le=10000,  # le = less than or equal to
        description="Maximum number of rows to return",
        example=500
    )
    
    # Future: Could add parameters like date filters, etc.
    # filters: Optional[Dict[str, Any]] = None


class UpdateReportRequest(BaseModel):
    """
    Data for updating an existing report
    All fields optional - only update what's provided
    
    User flow:
    1. User edits report name/description/tags
    2. Frontend sends PATCH /reports/{id}
    """
    
    report_name: Optional[str] = Field(
        None,
        min_length=1,
        max_length=255,
        description="New report name"
    )
    
    report_description: Optional[str] = Field(
        None,
        max_length=1000,
        description="New report description"
    )
    
    tags: Optional[List[str]] = Field(
        None,
        description="New tags (replaces existing)"
    )
    
    is_favorite: Optional[bool] = Field(
        None,
        description="Mark as favorite"
    )


